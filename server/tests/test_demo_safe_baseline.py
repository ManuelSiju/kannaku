"""The 5 demo cases with every FEATURE_* flag off must match the `demo-safe` tag: verdicts, facts and spoken lines.

tests/fixtures/demo_safe_baseline.json was written at that tag and is never regenerated by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.api import deps
from app.config import SERVER_ROOT, get_settings
from app.main import app
from app.pipeline.events import EventBus
from tests.fakes import FakeLLM, FakeSTT, load_fixture

BASELINE = Path(__file__).parent / "fixtures" / "demo_safe_baseline.json"
BROCHURE = SERVER_ROOT / "demo_assets" / "kanakavalli_brochure.pdf"
FLAGS = ("FEATURE_MEMBERS", "FEATURE_HOLDINGS", "FEATURE_TRACE_EXPORT", "FEATURE_SNAPSHOT")
CASES = {
    "endowment": ("An agent from the company says this plan is guaranteed to give 15 lakh. Should I take it?", True),
    "flat_loan": (
        "A finance company is offering me a loan of 1,00,000 at 12% flat for 24 months. Should I take it?",
        0,
    ),
    "stock_tip": (
        "I got this message: ZEPHYRX LTD - BIG NEWS COMING! Target Rs. 180 in 2 weeks. Upper circuit guaranteed. "
        "Should I put 1 lakh in it?",
        False,
    ),
    "otp_scam": ("A man from the bank called. My KYC has expired and he asks me to tell him the OTP.", False),
    "out_of_scope": ("How do I make sambar?", False),
}


def run_case(repo, name: str, privacy: str) -> dict:
    question, brochure = CASES[name]
    llm = FakeLLM({} if name == "otp_scam" else load_fixture(name))
    app.dependency_overrides[deps.get_repo] = lambda: repo
    app.dependency_overrides[deps.get_llm_provider] = lambda: llm
    app.dependency_overrides[deps.get_stt_provider] = lambda: FakeSTT("")
    app.dependency_overrides[deps.get_bus] = EventBus
    files = [("files", (BROCHURE.name, BROCHURE.read_bytes(), "application/pdf"))] if brochure else None
    try:
        with TestClient(app) as client:
            data = {"family_id": "1", "text": question, "earphones": str(privacy == "full").lower()}
            res = client.post("/cases", data=data, files=files).json()
            bundle = client.get(f"/cases/{res['case_id']}").json()
    finally:
        app.dependency_overrides.clear()
    return {
        "mode": res["privacy_mode"],
        "colour": res["verdict"]["colour"],
        "case_type": res["case_type"],
        "called_agents": res["called_agents"],
        "llm_calls": res["llm_calls"],
        "facts": {f["id"]: [f["value"], f["status"], f["unit"], f["kind"]] for f in bundle["facts"]},
        "spoken": [[ln["speaker"], ln["text"]] for ln in res["spoken_lines"]],
    }


@pytest.mark.parametrize("privacy", ["discreet", "full"])
@pytest.mark.parametrize("name", CASES)
def test_flags_off_matches_demo_safe(demo_repo, monkeypatch, name, privacy):
    for flag in FLAGS:
        monkeypatch.setenv(flag, "false")
    get_settings.cache_clear()
    try:
        assert run_case(demo_repo, name, privacy) == json.loads(BASELINE.read_text())[privacy][name]
    finally:
        get_settings.cache_clear()
